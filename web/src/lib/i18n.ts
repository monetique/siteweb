/**
 * Langues du site : français à la racine (/), anglais (/en/) et arabe (/ar/, écriture de droite à gauche).
 * Ce module ne dépend que de JavaScript standard : il est utilisable côté serveur comme côté navigateur.
 * Les textes éditoriaux viennent de Strapi (une version par langue) ; ce dictionnaire ne couvre que
 * les libellés de l'interface (boutons, formulaires, fil d'Ariane…).
 */
export const LANGS = ["fr", "en", "ar"] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = "fr";
export const isLang = (v: unknown): v is Lang => LANGS.includes(v as Lang);
export const dirOf = (lang: Lang) => (lang === "ar" ? "rtl" : "ltr");

/** Code de langue des dates et nombres : chiffres latins partout (usage des documents SMT). */
export const INTL: Record<Lang, string> = { fr: "fr-FR", en: "en-GB", ar: "ar-TN-u-nu-latn" };
export const OG_LOCALE: Record<Lang, string> = { fr: "fr_TN", en: "en_GB", ar: "ar_TN" };
export const LANG_LABEL: Record<Lang, string> = { fr: "FR", en: "EN", ar: "عربي" };
export const LANG_NAME: Record<Lang, string> = { fr: "Français", en: "English", ar: "العربية" };

/** Préfixe une adresse interne avec la langue (/solutions/ → /en/solutions/). Les liens externes sont inchangés. */
export function localizePath(href: string, lang: Lang): string {
  if (!href || !href.startsWith("/") || href.startsWith("//")) return href;
  const bare = stripLang(href);
  if (lang === DEFAULT_LANG) return bare;
  return bare === "/" ? `/${lang}/` : `/${lang}${bare}`;
}

/** Retire le préfixe de langue d'un chemin (/ar/contact/ → /contact/). */
export function stripLang(path: string): string {
  const m = path.match(/^\/(en|ar)(\/.*|$)/);
  if (!m) return path;
  return m[2] || "/";
}

/** Langue d'un chemin d'URL. */
export const langOfPath = (path: string): Lang => (path.match(/^\/(en|ar)(\/|$)/)?.[1] as Lang) ?? DEFAULT_LANG;

/* ------------------------------------------------------------------ formats */
export const formatDate = (iso: string | null | undefined, lang: Lang, opts: Intl.DateTimeFormatOptions = { day: "numeric", month: "long", year: "numeric" }) =>
  iso ? new Intl.DateTimeFormat(INTL[lang], { timeZone: "Africa/Tunis", ...opts }).format(new Date(iso)) : "";

export const formatDateTime = (iso: string | null | undefined, lang: Lang) =>
  iso ? new Intl.DateTimeFormat(INTL[lang], { timeZone: "Africa/Tunis", dateStyle: "full", timeStyle: "short" }).format(new Date(iso)) : "";

export const formatEvolution = (n: number | null | undefined, lang: Lang) =>
  n === null || n === undefined ? "" : `${n > 0 ? "+" : n < 0 ? "−" : ""}${Math.abs(n).toLocaleString(INTL[lang])} %`;

/**
 * Périodes statistiques saisies une seule fois dans Strapi (« Juin 2025 », « 2024 ») : le mois est
 * traduit à l'affichage, les chiffres restent communs aux trois langues.
 */
const MONTHS_FR = ["janvier", "février", "mars", "avril", "mai", "juin", "juillet", "août", "septembre", "octobre", "novembre", "décembre"];
export function localizePeriod(period: string, lang: Lang): string {
  if (lang === "fr" || !period) return period;
  const m = period.trim().match(/^([A-Za-zÀ-ÿ]+)\s+(\d{4})(.*)$/);
  const idx = m ? MONTHS_FR.indexOf(m[1].toLowerCase()) : -1;
  if (!m || idx < 0) return period;
  const month = new Intl.DateTimeFormat(INTL[lang], { month: "long", timeZone: "UTC" }).format(new Date(Date.UTC(2000, idx, 15)));
  return `${month} ${m[2]}${m[3]}`;
}

